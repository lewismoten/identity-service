import fs from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const dbDir = path.resolve(projectRoot, process.env.DB_DIR ?? "db");
const outFile = path.resolve(projectRoot, process.env.OUT_FILE ?? path.join("db", "build.sql"));

const isSqlFile = p => p.toLowerCase().endsWith(".sql");
const toPosix = p => p.split(path.sep).join("/");

/** @param {fs.Dirent} dirEnt */
/** @returns {boolean} */
const isHidden = dirEnt => dirEnt.name.startsWith('.');

/** @param {fs.Dirent} dirEnt */
/** @returns {boolean} */
const isNodeModules = dirEnt => dirEnt.isDirectory() && dirEnt.name === 'node_modules';

/** @param {string} dirAbs */
/** @returns {string[]} */
const listSqlFilesRecursive = dirAbs => {
  /** @param {string} p */
  /** @returns {string[]} */
  const walk = p => fs.readdirSync(p, { withFileTypes: true })
    .reduce(
      /** @param {string[]} all */
      /** @param {fs.Dirent} dirEnt */
      /** @returns {string[]} */
      (all, dirEnt) => {
      if (isHidden(dirEnt) || isNodeModules(dirEnt)) return all;
      const abs = path.join(p, dirEnt.name);
      if (dirEnt.isDirectory()) {
        all.push(...walk(abs));
      } else if (dirEnt.isFile() && isSqlFile(abs)) {
        all.push(abs);
      }
      return all;
    }, []);
  return walk(dirAbs);
}

/** @param {string} segment */
const leadingNumber = segment => {
  const m = segment.match(/^(\d+)/);
  return m ? Number(m[1]) : Number.POSITIVE_INFINITY;
}

/** @param {string} rel */
/** @param {string} thatRel */
/** @returns {number} */
const comparePathsForBuild = (rel, thatRel) => {
  const segment = toPosix(rel).split("/");
  const thatSegment = toPosix(thatRel).split("/");

  const len = Math.max(segment.length, thatSegment.length);
  for (let i = 0; i < len; i++) {
    const as = segment[i] ?? "";
    const bs = thatSegment[i] ?? "";

    const an = leadingNumber(as);
    const bn = leadingNumber(bs);
    if (an !== bn) return an - bn;
    const lc = as.localeCompare(bs);
    if (lc !== 0) return lc;
  }
  return 0;
}

const ensureDirExists = fileAbs => fs.mkdirSync(
  path.dirname(fileAbs), 
  { recursive: true }
);

const main = () => {
  if (!fs.existsSync(dbDir) || !fs.statSync(dbDir).isDirectory()) {
    console.error(`DB directory not found: ${dbDir}`);
    process.exit(1);
  }

  const absPaths = listSqlFilesRecursive(dbDir);

  const relPaths = absPaths
    .map(absPath => path.relative(projectRoot, absPath))
    .map(toPosix);

  const outRel = toPosix(path.relative(projectRoot, outFile));
  const filtered = relPaths.filter(relPath => relPath !== outRel);

  const sorted = filtered.sort(comparePathsForBuild);

  const sourceDirRel = toPosix(path.relative(projectRoot, dbDir)) || "db";

  const header = `
/*
db/build.sql (AUTO-GENERATED)
Generated by scripts/generate-build-sql.mjs
Source directory: ${sourceDirRel}
*/

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS=0;
`;

  const lines = sorted.map(relPath => `

/* ---------------------------------------------------------
FILE: ${relPath}
--------------------------------------------------------- */

${fs.readFileSync(relPath, { encoding: 'utf8'})}
`);

  const footer = `
SET FOREIGN_KEY_CHECKS=1;
`
  const content = header + lines.join("\n") + footer;

  ensureDirExists(outFile);
  fs.writeFileSync(outFile, content, "utf8");

  console.log(`Generated ${outRel}`);
  console.log(`Included ${sorted.length} SQL files.`);
}

main();