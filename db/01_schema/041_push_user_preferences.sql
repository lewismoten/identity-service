CREATE TABLE IF NOT EXISTS push_user_preferences (
  user_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  login_alerts TINYINT(1) NOT NULL DEFAULT 1,
  mfa_prompts  TINYINT(1) NOT NULL DEFAULT 1,
  security_notices TINYINT(1) NOT NULL DEFAULT 1,
  product_announcements TINYINT(1) NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_push_prefs_user
    FOREIGN KEY (user_id) REFERENCES users(id)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
